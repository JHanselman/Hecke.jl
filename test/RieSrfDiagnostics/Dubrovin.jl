################################################################################
#
#  RieSrfDiagnostics/Dubrovin.jl : the quartics of the Dubrovin threefold
#  (dubrovin_quartics, Agostini-Celik-Eken) against the reconstruction from
#  the gradients of the odd theta functions (reconstruct_curve). Not part of
#  the test run; load after the package:
#
#    using Hecke, Test
#    include("test/RieSrf/setup_tests.jl")
#    include("test/RieSrf/Reconstruction/setup_tests.jl")
#    include("test/RieSrfDiagnostics/Reconstruction.jl")
#    include("test/RieSrfDiagnostics/Dubrovin.jl")
#    dubrovin_benchmark(; genera = 3:6)
#
#  For each curve (in the coordinates of its differentials, over QQ):
#
#   - the times of the theta functions of both methods (Dubrovin: jets of
#     order 4 of the 2^g second order theta functions at 2 tau, computed
#     twice: once alone, once in the numerical quartics; ours: the 4^g theta
#     constants at tau), of the numerical quartics and of both
#     reconstructions over QQ (including the theta functions);
#   - `bits`: log2 of the difference between the numerical echelon form of
#     the quartics and the exact one, relative (about -prec plus the loss);
#   - whether the quartics lie in the ideal of the curve (the exact
#     generators if known, otherwise those of reconstruct_curve) and whether
#     both methods agree.
#
################################################################################

# log2 of the largest difference between the numerical echelon form E (pivot
# columns `pivots`, columns `monomials`) and the echelon form of the exact
# forms with the same pivots, relative to its largest entry
function _echelon_difference_log2(E::AcbMatrix, pivots, monomials, exact)
  A = matrix(QQ, length(exact), length(monomials), [QQ(coeff(f, m)) for f in exact for m in monomials])
  rank(A) == nrows(E) || return Inf
  B = A[:, pivots]
  iszero(det(B)) && return Inf
  X = inv(B) * A
  CC = base_ring(E)
  difference = maximum(RSM._abs64(E[r, c] - CC(X[r, c])) for r in 1:nrows(X), c in 1:ncols(X))
  return RSM._safe_log2(difference / maximum(abs(Float64(c)) for c in X))
end

# whether the forms of degree d lie in the ideal generated by `generators`
# (in degree d, exactly over QQ)
function _in_ideal(forms, generators, d::Int)
  S = parent(forms[1])
  g = nvars(S)
  x = gens(S)
  to_S(q) = map_coefficients(c -> QQ(c), q; parent = S)
  multiples = elem_type(S)[]
  for q in generators
    k = total_degree(q)
    k <= d || continue
    for e in RSM._exponent_vectors(g, d - k)
      push!(multiples, to_S(q) * prod(x[i]^e[i] for i in 1:g))
    end
  end
  isempty(multiples) && return false
  ed = RSM._exponent_vectors(g, d)
  M(fs) = matrix(QQ, length(fs), length(ed), [QQ(coeff(f, e)) for f in fs for e in ed])
  return rank(vcat(M(multiples), M(forms))) == rank(M(multiples))
end

@doc raw"""
    compare_dubrovin(P; exact = nothing, ours = true) -> NamedTuple

The comparison described at the top of the file for the big period matrix
`P` (rows: differentials over QQ). `exact`: exact generators of the ideal in
these coordinates (if known); `ours = false` skips reconstruct_curve.
"""
function compare_dubrovin(P::AcbMatrix; exact = nothing, ours::Bool = true)
  g = nrows(P)
  prec = precision(base_ring(P))
  CC = base_ring(P)
  T, tau_red = Hecke.siegel_reduction(RSM._small_period_matrix(P))
  # the steps of dubrovin_quartics(P, QQ), timed separately
  t_jets = @elapsed RSM._second_order_theta_jets(2 * tau_red, [0, 2, 4])
  t_numerical = @elapsed begin
    forms, data = RSM._dubrovin_quartics(tau_red)
    L = RSM._coordinates_from_differentials(P, tau_red, T, identity_matrix(CC, g))
    Q = RSM._substitute_coordinates(forms, L)
    A, monomials = RSM._coefficient_matrix(Q, 4)
    E, pivots = RSM._numerical_rref(A)
    numerical = (rref = E, pivots = pivots, monomials = monomials, info = data.info)
  end
  t_dubrovin = @elapsed quartics = try RSM._recognize_forms(Q, 4, QQ, nothing; what = "quartic") catch err; err end
  t_dubrovin += t_numerical
  recognized = !(quartics isa Exception)
  model = nothing
  t_thetas = t_ours = NaN
  if ours && g >= 4
    t_thetas = @elapsed RSM.theta_constants(tau_red)
    t_ours = @elapsed model = try RSM.reconstruct_curve(P, QQ) catch err; err end
  end
  ours_ok = model !== nothing && !(model isa Exception)
  reference = exact !== nothing ? exact : ours_ok ? model : nothing
  bits = recognized && reference !== nothing ? _echelon_difference_log2(numerical.rref, numerical.pivots, numerical.monomials, quartics) : NaN
  in_ideal = recognized && reference !== nothing ? _in_ideal(quartics, reference, 4) : missing
  agree = exact !== nothing && ours_ok ? all(d -> _in_ideal(exact, model, d), unique(total_degree.(exact))) : missing
  return (genus = g, precision = prec, quartics = recognized ? length(quartics) : 0,
          recognized = recognized, bits = bits, in_ideal = in_ideal,
          time_jets = t_jets, time_numerical = t_numerical, time_dubrovin = t_dubrovin,
          time_thetas = t_thetas, time_ours = t_ours, ours = ours_ok, ours_agree = agree,
          kernel = numerical.info.kernel, error = recognized ? nothing : quartics,
          ours_error = model isa Exception ? model : nothing)
end

# A plane curve f over QQ: its big period matrix (Baker's basis) and, for
# genus 3, the exact quartic in these coordinates is not known (nothing).
function _dubrovin_plane_case(f, prec)
  RS = RSM.riemann_surface(f, prec; superelliptic = false, model = :original)
  return RSM.big_period_matrix(RS)
end

@doc raw"""
    dubrovin_benchmark(; genera = 3:6, seed = 4711) -> Vector

compare_dubrovin on fixed test curves of the given genera, printed as a
table: genus 3 (Trott's quartic), genus 4 (generic, vanishing theta null),
genus 5 (canonical_test_curve, the trigonal test curve), genus 6
(canonical_test_curve, a plane quintic).
"""
function dubrovin_benchmark(; genera = 3:6, seed::Int = 4711)
  Hecke.Random.seed!(seed)
  R, (x, y) = polynomial_ring(QQ, [:x, :y]; cached = false)
  cases = Any[]
  if 3 in genera
    push!(cases, ("g3 Trott", () -> (_dubrovin_plane_case(144*x^4 + 144*y^4 - 225*x^2 - 225*y^2 + 350*x^2*y^2 + 81, 200), nothing)))
  end
  if 4 in genera
    for kind in (:generic, :theta_null)
      f = _random_g4_curve(kind)
      push!(cases, ("g4 $kind", () -> (_dubrovin_plane_case(f, 300), nothing)))
    end
  end
  for g in intersect(genera, 5:7)
    curve = g == 5 ? canonical_test_curve_g5() : canonical_test_curve(g)
    push!(cases, ("g$g generic", () -> begin
      RS = g == 5 ? RSM.riemann_surface(curve.plane, 100 * g; superelliptic = false, model = :original) :
                    riemann_surface_with_differentials(curve.plane, curve.numerators, 100 * g)
      P = g == 5 ? period_matrix_of_differentials(RS, curve.plane, curve.numerators) : RSM.big_period_matrix(RS)
      (P, curve.quadrics)
    end))
  end
  5 in genera && push!(cases, ("g5 trigonal", () -> (_dubrovin_plane_case(trigonal_test_curve(), 400), nothing)))
  6 in genera && push!(cases, ("g6 plane quintic", () -> (_dubrovin_plane_case(plane_quintic_test_curve(), 500), nothing)))
  results = Any[]
  println(rpad("curve", 18), lpad("prec", 6), lpad("#", 5), lpad("bits", 8), lpad("ideal", 7),
          lpad("jets", 9), lpad("dub CC", 9), lpad("dub QQ", 9), lpad("thetas", 9), lpad("ours QQ", 9), lpad("agree", 7))
  for (name, make) in cases
    t_periods = @elapsed (P, exact) = make()
    r = compare_dubrovin(P; exact = exact)
    push!(results, merge((name = name, time_periods = t_periods), r))
    s(t) = isnan(t) ? "-" : string(round(t, digits = 1))
    println(rpad(name, 18), lpad(r.precision, 6), lpad(r.quartics, 5), lpad(isnan(r.bits) ? "-" : string(round(r.bits, digits = 0)), 8),
            lpad(string(r.in_ideal), 7), lpad(s(r.time_jets), 9), lpad(s(r.time_numerical), 9), lpad(s(r.time_dubrovin), 9),
            lpad(s(r.time_thetas), 9), lpad(s(r.time_ours), 9), lpad(string(r.ours_agree), 7))
    r.error === nothing || println("    Dubrovin: ", first(sprint(showerror, r.error), 200))
    r.ours_error === nothing || println("    ours: ", first(sprint(showerror, r.ours_error), 200))
    flush(stdout)
  end
  return results
end
