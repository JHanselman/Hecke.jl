################################################################################
#
#  CurveReconstruction.jl : a model of the curve from its theta constants or
#  period matrix (all genera)
#
#  reconstruct_curve decides the type of the curve and calls the method for
#  it:
#
#   g <= 3        ReconstructCurvesG123.jl (Rosenhain, Weber);
#   g = 4         ReconstructG4.jl (Hanselman-Pieper-Schiavone);
#   g >= 5:
#     hyperelliptic   2^(g-1)(2^g + 1) - binom(2g + 1, g) even theta
#                     constants vanish: Rosenhain form by Takase's formula
#                     (Hyperelliptic.jl);
#     generic         no even theta constant vanishes and the quadrics
#                     (Quadrics.jl) cut out the canonical model (Petri);
#     trigonal or     the quadrics cut out a surface (a scroll, resp. the
#     plane quintic   Veronese surface for a plane quintic, g = 6): they have
#                     more linear syzygies than for a generic curve. The
#                     cubics through the canonical model come from quartics
#                     that are 2 x 2 minors of the matrix of the images of
#                     the monomials of the Prym (_cubics_through_curve); for a
#                     plane quintic also the plane model (PlaneQuintic.jl).
#
#  Over K (QQ or a number field) from a big period matrix whose rows are
#  differentials defined over K: the forms are moved to the coordinates of
#  these differentials and recognized (as for the quadrics in Quadrics.jl).
#
#  Entry points: reconstruct_curve, reconstruct_curve_data.
#
################################################################################

################################################################################
#
#  Trigonal curves and plane quintics: the cubics
#
################################################################################

# The (g - 1) x (g - 1) symmetric matrix of the quadrics phi(y_a y_b), in
# the ring R of the quadrics (the coordinates of K). phi maps the quadrics in
# the coordinates of the Prym gradients to quadrics in those of K by
# m_d^2 -> l_kappa(d) l_kappa(d)+eta; it is well defined modulo the quadrics
# through the curve. On the curve the matrix has rank 1, so its 2 x 2 minors
# are quartics through the canonical model.
function _prym_monomial_quadrics(g::Int, K::AcbMatrix, K_prym::AcbMatrix, R::MPolyRing)
  CC = base_ring(K)
  lower(n) = [(i, j) for j in 1:n for i in j:n]
  index_pairs = lift_prym_indices(g)
  n = length(index_pairs)
  m = length(lower(g - 1))
  products = zero_matrix(CC, n, length(lower(g)))
  squares = zero_matrix(CC, n, m)
  for (d, (i1, i2)) in enumerate(index_pairs)
    for (k, (a, b)) in enumerate(lower(g))
      products[d, k] = K[i1, a] * K[i2, b] + K[i2, a] * K[i1, b]
    end
    for (k, (a, b)) in enumerate(lower(g - 1))
      squares[d, k] = K_prym[d, a] * K_prym[d, b]
    end
  end
  # m of the squares m_d^2 that are a basis of the quadrics in g - 1 variables
  basis = _numerical_kernel_data(transpose(squares); nullity = n - m).pivot_columns
  basis_squares = matrix(CC, m, m, [squares[d, k] for k in 1:m for d in basis])
  # column k: the combination of the basis squares that is the entry k
  alpha = _solve_precond(basis_squares, identity_matrix(CC, m))
  images = matrix(CC, length(lower(g)), m, [products[d, k] for k in 1:length(lower(g)) for d in basis]) * alpha
  x = gens(R)
  half = inv(CC(2))
  form(k) = sum((a == b ? half : one(CC)) * images[s, k] * x[a] * x[b] for (s, (a, b)) in enumerate(lower(g)))
  forms = [form(k) for k in 1:m]
  slot = Dict(p => k for (k, p) in enumerate(lower(g - 1)))
  return [i == j ? forms[slot[(i, i)]] : half * forms[slot[(max(i, j), min(i, j))]] for i in 1:g-1, j in 1:g-1]
end

# The dimension of the cubics in the ideal generated by the quadrics (the
# rank of the multiples x_a q), and the dimension for a generic canonical
# curve, C(g + 2, 3) - (5g - 5). Smaller: trigonal or a plane quintic.
function _quadric_multiples_rank(quadrics)
  g = nvars(parent(quadrics[1]))
  x = gens(parent(quadrics[1]))
  S3, monomials = _coefficient_matrix([x[a] * q for q in quadrics for a in 1:g], 3)
  Z3 = numerical_kernel(S3)[1]
  return length(monomials) - ncols(Z3), binomial(g + 2, 3) - (5*g - 5)
end

# All cubics through the canonical model (columns of a matrix over CC in the
# monomials _exponent_vectors(g, 3)) and the cubics among them that are not
# in the ideal of the quadrics: a cubic c is in I_3 if all x_m c are in I_4,
# which is spanned by the multiples x_a x_b q of the quadrics and the minors
# of _prym_monomial_quadrics.
function _cubics_through_curve(quadrics, M)
  R = parent(quadrics[1])
  CC = base_ring(R)
  g = nvars(R)
  x = gens(R)
  e3 = _exponent_vectors(g, 3)
  e4 = _exponent_vectors(g, 4)
  n = g - 1
  multiples = [x[a] * x[b] * q for q in quadrics for a in 1:g for b in a:g]
  minors = [M[i, k] * M[j, l] - M[i, l] * M[j, k] for i in 1:n for j in i+1:n for k in 1:n for l in k+1:n]
  S4, _ = _coefficient_matrix(filter(!iszero, [multiples; minors]), 4)
  # the linear forms on the quartics that vanish on I_4
  Z4 = numerical_kernel(S4)[1]
  position = Dict(e => k for (k, e) in enumerate(e4))
  nz = ncols(Z4)
  conditions = zero_matrix(CC, g * nz, length(e3))
  for m in 1:g, (s, e) in enumerate(e3)
    shifted = copy(e)
    shifted[m] += 1
    r = position[shifted]
    for t in 1:nz
      conditions[(m - 1) * nz + t, s] = Z4[r, t]
    end
  end
  all_cubics = numerical_kernel(conditions)[1]
  # the linear forms on the cubics that vanish on the multiples x_a q
  S3, _ = _coefficient_matrix([x[a] * q for q in quadrics for a in 1:g], 3)
  Z3 = numerical_kernel(S3)[1]
  outside = _numerical_kernel_data(transpose(Z3) * all_cubics).pivot_columns
  cubic(c) = sum(all_cubics[s, c] * prod(x[j]^e3[s][j] for j in 1:g) for s in eachindex(e3))
  return [cubic(c) for c in 1:ncols(all_cubics)], [cubic(c) for c in outside]
end

