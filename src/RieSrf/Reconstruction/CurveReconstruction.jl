@doc raw"""
    reconstruct_curve_data(tau::AcbMatrix; kw...) -> NamedTuple
    reconstruct_curve_data(thetas::AbstractDict; kw...) -> NamedTuple

reconstruct_curve together with the type of the curve (`case`: :generic,
:hyperelliptic, :trigonal or :plane_quintic for g >= 5) and the data of the
computation (`quadrics`, `cubics`, `data` (see
reconstruct_quadrics_from_thetas), ...). With `plane_model = false` a plane
quintic is returned as its canonical model (quadrics and cubics) instead of
the plane quintic of Masiewicki's construction. For g <= 4 see
reconstruct_curve_from_tau and reconstruct_curve_g4_data.
"""
function reconstruct_curve_data(tau::AcbMatrix; kw...)
  g = nrows(tau)
  @req ncols(tau) == g && g >= 5 "tau must be a g x g matrix with g >= 5 (for g <= 4 use reconstruct_curve)."
  thetas, tau_red, T = _reduced_theta_constants(tau)
  return _curve_from_thetas(g, thetas; prec = precision(base_ring(tau)), tau = tau_red, transform = T, kw...)
end

function reconstruct_curve_data(thetas::AbstractDict; kw...)
  thetas = _theta_constants_avoiding_prym(thetas)
  return _curve_from_thetas(_genus_of_thetas(thetas), thetas; kw...)
end

@doc raw"""
    reconstruct_curve(tau::AcbMatrix; kw...)
    reconstruct_curve(thetas::AbstractDict; kw...)
    reconstruct_curve(P::AcbMatrix, K; place = nothing, normalize = true, reduce_units = true, kw...)

A model of the curve with small period matrix `tau` (g x g), with theta
constants `thetas` (a dictionary as returned by Hecke.thetas, g >= 5), or
with big period matrix `P` (g x 2g) whose rows are a basis of differentials
defined over K (QQ or a number field, embedded by `place`), e.g.
big_period_matrix(RS) for a curve RS over K. The model:

 - g = 1, 2, 3 (over CC): see reconstruct_curve_from_tau;
 - g = 4: the quadric and the cubic of the canonical model (over K:
   reconstruct_rational_curve_g4), or the hyperelliptic curve;
 - g >= 5, generic: the quadrics through the canonical model (reconstruct_quadrics);
 - g >= 5, trigonal: these quadrics and the cubics that, together with them,
   cut out the canonical model;
 - g = 6, plane quintic: over CC the plane quintic (Masiewicki's construction,
   reconstruct_plane_quintic); over K the canonical model (quadrics and cubics);
 - g >= 5, hyperelliptic: the hyperelliptic curve y^2 = f(x); over CC in
   Rosenhain form (Takase's formula), over K from the gradients of the odd
   theta functions, up to a quadratic twist (the rows of P must be the
   differentials x^(j-1) dx / y, j = 1..g, see reconstruct_hyperelliptic_curve).

Over CC the canonical models are in coordinates that are determined only up
to a linear change. The theta constants of the curve are those of FLINT;
keywords (`sign_data`, `fay_relations`, ...) as for reconstruct_quadrics.
"""
function reconstruct_curve(tau::AcbMatrix; kw...)
  g = nrows(tau)
  ncols(tau) == 2*g && return reconstruct_curve(tau, nothing; kw...)
  @req ncols(tau) == g "tau must be a square matrix."
  g <= 4 && return reconstruct_curve_from_tau(tau)
  return reconstruct_curve_data(tau; kw...).curve
end

reconstruct_curve(thetas::AbstractDict; kw...) = reconstruct_curve_data(thetas; kw...).curve

function reconstruct_curve(P::AcbMatrix, K; place = nothing, normalize::Bool = true,
                           reduce_units::Bool = true, kw...)
  g = nrows(P)
  @req ncols(P) == 2*g "P must be a g x 2g matrix."
  tau = _small_period_matrix(P)
  if K === nothing
    g <= 4 && return reconstruct_curve_from_tau(tau)
    return reconstruct_curve_data(tau; kw...).curve
  end
  g == 4 && return reconstruct_rational_curve_g4(P, K; place, normalize, reduce_units)
  @req g >= 4 "Over QQ or a number field only for g >= 4 (use reconstruct_curve(tau) for g <= 3)."
  data = reconstruct_curve_data(tau; plane_model = false, kw...)
  data.case === :hyperelliptic && return reconstruct_hyperelliptic_curve(P, K; place)
  B, q_B = _gradient_coordinates(data.tau, data.data.gradients)
  @req q_B < -precision(base_ring(P)) / 4 "The gradient kernel is not a linear image of the theta gradients (log2 residual $q_B)."
  CC = base_ring(data.tau)
  L = _coordinates_from_differentials(change_base_ring(CC, P), data.tau, data.transform, B)
  quadrics = _recognize_forms(_substitute_coordinates(data.quadrics, L), 2, K, place;
                              normalize, reduce_units, what = "quadric")
  data.case === :generic && return quadrics
  # the cubics: the echelon basis of all cubics through the curve over K, of
  # which those outside the ideal of the quadrics are kept (exactly)
  all_cubics = _recognize_forms(_substitute_coordinates(data.all_cubics, L), 3, K, place;
                                normalize = false, what = "cubic")
  S = parent(all_cubics[1])
  quadrics_S = [map_coefficients(c -> base_ring(S)(c), q; parent = S) for q in quadrics]
  x = gens(S)
  multiples = [x[a] * q for q in quadrics_S for a in 1:g]
  e3 = _exponent_vectors(g, 3)
  rows(fs) = matrix(base_ring(S), length(fs), length(e3), [coeff(f, e) for f in fs for e in e3])
  kept = elem_type(S)[]
  current = rank(rows(multiples))
  for c in all_cubics
    r = rank(rows([multiples; kept; c]))
    if r > current
      push!(kept, c)
      current = r
    end
  end
  cubics = normalize ? [_normalize_model(c; reduce_units) for c in kept] : kept
  return [quadrics_S; cubics]
end
